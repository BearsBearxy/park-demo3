-- 启用账期回填(2026-08-14 用户报障:「为什么我导入23年8月的抄表读数还是会出现后面月份才有的电表」)。
--
-- 症状:2023-08 一期电表里出现「旭化成 电表⑤」两块(编码 230828010084 / 202005200003),
-- 而用户手上的 2023年8月源册根本没有这两行 —— 它们最早的读数是 2023-10。
--
-- 根因:active_from_ym 为空 = 「一直在册」,于是这类表在**每一个**月份都显示,与导入哪个月无关。
-- V87 建列时只回填了「202405 种子建档且至今零读数」那一小撮,其余一律留空;
-- 而导入侧只有两条路会写它:①新建档 → 落首现月(MeterService:325);
-- ②已有表且**启用月非空**时,导入更早月份自动放宽(MeterService:337 的 `!= null` 守卫)。
-- 于是「建档时没落启用月」的表掉进死角:导入早月不会给它补,导入晚月也不会把它推后,永远悬在所有月份。
-- 导入 2023-08 帮不上忙 —— 它压根不在那份源册里,导入见不到它。
--
-- 回填口径:启用月 = 该表**最早有读数的账期**。这与新建档走的是同一条规则(首现月=源册里第一次见到它),
-- 只是补做给那些建档时没落的表。零读数表不动(无从推断,维持「一直在册」)。
--
-- 影响面(dev 库 2026-08-14 实测 806 块):
--   757 块 → 2023-08(全库最早数据月,月份 ≥2023-08 的视图一格不变)
--     4 块 → 2023-10
--    45 块 → 2024-02
--   后两组共 49 块正是「漏进 2023-08 却没有 2023-08 读数」的那批,回填后从早月消失。
--
-- 可逆:判反了就在抄表屏抽屉「启用账期」改回来(留空=恢复「一直在册」);
-- 若日后导入更早月份的源册确实含此表,MeterService 的自愈会自动把启用月放宽回去,不用人工。
UPDATE meter m
JOIN (SELECT meter_id, MIN(ym) first_ym FROM meter_reading GROUP BY meter_id) f
  ON f.meter_id = m.id
SET m.active_from_ym = f.first_ym
WHERE m.active_from_ym IS NULL;
