-- V76__meter_loc_manual.sql — 位置三列是否人工设定(刀F §F6:§E7 的 spec 级缺口修正)。
--
-- 刀E §E7 为了不让导入冲掉人工改过的楼层/方位/房号,把导入侧写成「已有值一律不动」。
-- 但 meter.floor_label 是 §D.1 楼层二级回退的数据源,直接决定 floor 池的桶数与逐户金额:
-- 一块表从三楼挪到五楼,导入把 spot 改成五楼、floor_label 停在三楼 → 桶算错、钱算错,
-- 而且屏上「位置原文」写五楼、「楼层」写三楼自相矛盾,零告警。
--
-- 改成按「是否人工设定过」分流(MeterService.applyDesc):
--   loc_manual=0(位置三列 == 按 spot 自动解析的结果):导入跟着新 spot 重解析,表挪地方自动跟上;
--   loc_manual=1(三列中任一与自动解析不同 = 人工覆盖,或 §E8 的显式清空「留空=跨层」):
--                导入一列不动;但位置原文**变了**且解析出的楼层与人工值不同时,落一条导入 warn 请人核对。
--
-- 标志位不由请求体传入,而是 MeterService.apply()(档案 POST/PUT)按「三列与自动解析是否有出入」
-- 自动维护 —— 抽屉里恒带全量三列(§A.3),客户端自报「我改过」不可信,派生才对得住。
-- 判据的副作用是良性的:人工把楼层设成与解析一致的值 = 没有信息量,继续自动跟随;
-- 人工改回与原文一致(或清掉自定义值)即恢复 0,不需要另开一个「取消人工」的口子。
--
-- 回填:V74 建列时三列全部由 spot 解析而来,刀A/刀E 之后的人工修改无从追溯,一律按 0(自动)起步。
-- 最坏情况是下次导入把当时的人工值按 spot 重解析回去,而那恰是本刀要的默认行为;人再改一次即永久置 1。

ALTER TABLE meter
  ADD COLUMN loc_manual TINYINT NOT NULL DEFAULT 0
  COMMENT '位置三列(楼层/方位/房号)是否人工设定:0=与位置原文解析一致,导入跟随重解析;1=人工设定,导入不动、原文变了只落warn';
