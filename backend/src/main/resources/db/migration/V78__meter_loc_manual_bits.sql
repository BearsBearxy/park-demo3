-- V78__meter_loc_manual_bits.sql — 刀G §G5:loc_manual 由「三列共用一个布尔」改成「逐列一位」的位掩码。
--
-- 病根(刀F 遗留):V76 的 loc_manual 是一个布尔,判据是「楼层/方位/房号**任一**与位置原文解析不一致」。
-- 于是人工只改了房号(或只改了方位),楼层也一并被永久冻结 —— 以后这块表挪了地方、导入把位置原文
-- 从三楼改成五楼,楼层却仍停在三楼,而楼层是 §D.1 floor 池的桶数依据,桶算错、逐户金额跟着错,零告警。
-- 冻住的是没人碰过的列,纯副作用。
--
-- 【选位掩码而不是三个 boolean 列】:语义完全等价,但位掩码不用加列、DTO/前端 ts 不用各多两格字段,
-- 判定与消费都是一次位与;三个 boolean 列除了「SQL 里肉眼好读」没有别的好处,却要多写三份读写。
-- 【选新建 V78 而不是改 G1 的 V77】:V77 是同批未应用的迁移,但它是另一把刀的独占文件;
-- 且本条改的是 V76 建的列、与 V77 的 owner_manual 无关,分开一条更好回溯(Flyway 迁移本就该一事一条)。
--
--   bit0 (1) = 楼层 floor_label
--   bit1 (2) = 方位 side
--   bit2 (4) = 房号 room_no
-- 判定与消费都在 MeterService(apply 派生 locManualMask;applyDesc 逐位分流),不落业务规则在 SQL 里。
--
-- 数据不用回填:V76 建列时全库落 0(=自动跟随),0 在新旧口径下同义;V76 之后由 apply() 写出的 1
-- 在新口径下读作「只有楼层是人工设定」,与它当时的实情一致或更宽松(不再多冻方位/房号),
-- 且下一次该表走 PUT 时按新判据整体重算,自愈。故本迁移只改列注释,不改任何一行数据。

ALTER TABLE meter
  MODIFY COLUMN loc_manual TINYINT NOT NULL DEFAULT 0
  COMMENT '位置三列是否人工设定(位掩码):bit0=1楼层/bit1=2方位/bit2=4房号;某位=0 该列跟着位置原文重解析,=1 该列导入不动、原文变了只落warn';
