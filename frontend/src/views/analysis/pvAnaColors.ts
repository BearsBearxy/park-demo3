// src/views/analysis/pvAnaColors.ts —— 光伏分栋分析屏 v4 的颜色字面值镜像(PV-ANALYSIS-SCREEN-V4 §1.2 / §1.5)。
//
// 为什么要镜像:
//   ECharts 的 option 是**纯 JSON**,序列化后交给 canvas 渲染,拿不到 DOM 也就拿不到
//   CSS 自定义属性 —— 写 `color: 'var(--hue-orange)'` 得到的不是橙色,是**图元静默不画**。
//   同理 `--hue-blue/--hue-orange/--hue-yellow` 在 tokens.css 里是 oklch(),而 canvas 2D 的
//   fillStyle 在部分目标浏览器上不认 oklch,给个不认识的颜色串 = 该图元不画且不报错。
//   所以这一份、且只有这一份文件,允许出现颜色字面值;屏上凡是走 CSS 的地方一律继续用
//   CSS 令牌变量,不许从这里取值往 style 里塞。先例:components/ana/anaTheme.ts。
//
// v4 起本屏不再用 ECharts(全部自绘 SVG / CSS Grid),镜像仍然要留:下面这些 hex 取自
// anaTheme.ts 的 CAT_COLORS 与浅蓝族,**tokens.css 里没有对应令牌**,写不成 var(--*)。
// 仍然只有这一份文件许写颜色字面值;tokens.css 里有的色(--hue-green 给 A2 ▲、
// --control-solid 给选中芯片)组件里照旧写 var(--*),不在这里抄。
//
// ── v4 的颜色分工 ─────────────────────────────────────────────────────────────
//   1. **期别三色** —— 只在「一栋一条 / 一栋一点」的图上出现:A2、L1、L3 行头、L7、B8、芯片点。
//      单栋仍不拥有私有色;三期橙在本屏只落在三期那几栋上。
//   2. **焦点蓝 #378ADD** —— 主序列与选中栋:B1 线、B3 选中栋、B7·B8 自用段、L2 柱、B9 趋势、B11。
//      与一期同值,两个名字分开存:「一期」是类别,「选中 / 主序列」是状态,以后单调其一不牵连另一个。
//   3. **方向与越界** —— 红 = 低于下沿 / 变点 / 观测值 / 超出外带(全屏唯一的负向与越界色);
//      琥珀 = 高于上沿 / 缺抄 / 损耗率 / 超出内带。红只标方向与越界,**不做严重度灯**。
//      缺抄与高于上沿同色,靠形状分(缺抄 = 底部刻度 / 格底色;出范围 = 白环点 / 段底色)。
//   4. **带** —— 浅蓝 #B5D4F4,各块按 §1.2 的透明度叠(B1 40% / B3 45% / B9 50% / B10 50%·25% / L2 20% / L4 85%)。
//   5. **墨阶** —— 参照线(锚点 / y=x / β=1)一律墨阶虚线,不用橙:橙让给三期与损耗 / 缺抄。
//      损耗是废掉的那部分,走墨阶,不是第三种蓝。
// 方向 / 状态不能只靠颜色:▲▼、位置、点半径三档、字重照旧保留。

