// src/views/analysis/pvAnaColors.ts —— 光伏分栋分析屏 v3 的颜色字面值镜像(spec §06.7)。
//
// 为什么要镜像:
//   ECharts 的 option 是**纯 JSON**,序列化后交给 canvas 渲染,拿不到 DOM 也就拿不到
//   CSS 自定义属性 —— 写 `color: 'var(--hue-orange)'` 得到的不是橙色,是**图元静默不画**。
//   同理 `--hue-blue/--hue-orange/--hue-yellow` 在 tokens.css 里是 oklch(),而 canvas 2D 的
//   fillStyle 在部分目标浏览器上不认 oklch,给个不认识的颜色串 = 该图元不画且不报错。
//   所以这一份、且只有这一份文件,允许出现颜色字面值;屏上凡是走 CSS 的地方一律继续用
//   CSS 令牌变量,不许从这里取值往 style 里塞。先例:components/ana/anaTheme.ts。
//
// 改 tokens.css 必须同步改这里:
//   镜像是手抄的,没有构建期校验。动了下列任一令牌(改值 / 改名 / 删除),就要回到本文件
//   把对应行连同注释里的行号一起更新 —— 否则图表颜色会停在旧值,而页面其余部分已经变了,
//   并排一看就出戏(anaTheme.ts 的字体栈曾经就这样漂了一个版本)。
//   行号取自 frontend/src/styles/tokens.css(截至 2026-09-02),仅供人工核对,允许有偏移。
//
// ── 颜色上岗的三条 ────────────────────────────────────────────────────────────
// 颜色只在有**真实维度**的地方上岗。这屏只认三种维度:
//   1. **焦点** —— 你在队列里点中的那一栋(FOCUS)
//   2. **类别** —— 真正不同种的东西(自消纳/上网/损耗;质量矩阵四态)
//   3. **告警** —— 出范围(OUT,且只在 L0/L1)
// 没有这三种维度的图**保持墨阶** —— 例如 ACF 单序列柱、α 排序的区间线。那不是"黑白难看",
// 是没有东西可编码,硬上色就是装饰。方向/状态也**不能只靠颜色**:▲▼、位置、形状通道全部保留。
//
// 全屏色相 ≤ 4(墨 + 蓝家族 + 橙 + 黄);13 栋没有任何一栋拥有自己的颜色;全屏不用红。

