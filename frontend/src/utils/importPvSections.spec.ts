describe('importPvSections — 光伏多段拆段', () => {
  it('按段标题切成 3 段并映射 phaseId', () => {
    const { sections } = importPvSections(matrix)
    expect(sections.length).toBe(3)
    expect(sections[0].records[0].phaseId).toBe('p1')
    expect(sections[1].records[0].phaseId).toBe('p2')
    expect(sections[2].records[0].phaseId).toBe('p3')
    expect(sections[0].label).toContain('一期')
  })

  it('逐月行入库,小计/合计行被跳过', () => {
    const { sections } = importPvSections(matrix)
    // 一期:3 逐月(09/10/01)+ 小计/合计跳过 → 3 条
    expect(sections[0].records.map(r => r.acctMonth)).toEqual(['2024-09', '2024-10', '2025-01'])
    // 三期:2 逐月
    expect(sections[2].records.map(r => r.acctMonth)).toEqual(['2025-12', '2026-01'])
  })

  it('记账月份/发生月份解析为 YYYY-MM,消纳/上网四列映射,总量列不导', () => {
    const { sections } = importPvSections(matrix)
    const r0 = sections[0].records[0]
    expect(r0).toMatchObject({
      phaseId: 'p1', acctMonth: '2024-09', occurMonth: '2024-08',
      selfKwh: 153825, selfAmt: 138291.56, gridKwh: 33600, gridAmt: 15220.8,
    })
    // 派生总量/总金额不进记录
    expect('gen' in r0).toBe(false)
    expect('fee' in r0).toBe(false)
  })

  it('二期跨年起始月(2025-06)正确解析,occurMonth 分离', () => {
    const { sections } = importPvSections(matrix)
    const r = sections[1].records[0]
    expect(r.acctMonth).toBe('2025-06')
    expect(r.occurMonth).toBe('2025-05')
  })
})
